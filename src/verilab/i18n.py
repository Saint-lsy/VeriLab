def normalize_language(value: str | None) -> str:
    if not value:
        return DEFAULT_LANGUAGE
    language = value.lower().split("-", maxsplit=1)[0]
    return language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def make_translator(language: str) -> Callable[..., str]:
    language = normalize_language(language)

    def translate(key: str, **values: object) -> str:
        message = MESSAGES[language].get(key, MESSAGES[DEFAULT_LANGUAGE].get(key, key))
        return message.format(**values)

    return translate


def make_labeler(language: str) -> Callable[[str, object], str]:
    language = normalize_language(language)

    def label(kind: str, value: object) -> str:
        text = str(value)
        if language != "zh":
            return text
        return ZH_LABELS.get(kind, {}).get(text.lower(), text)

    return label
